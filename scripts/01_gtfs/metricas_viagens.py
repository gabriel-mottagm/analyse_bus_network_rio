import pandas as pd, numpy as np, sys, os
D=sys.argv[1]
def r(n,**k): return pd.read_csv(os.path.join(D,n+'.txt'),keep_default_na=False,**k)
def secs(t): 
    p=t.str.split(':',expand=True).astype(int); return p[0]*3600+p[1]*60+p[2]
ag=r('agency',dtype=str); ro=r('routes',dtype=str); tr=r('trips',dtype=str); st=r('stops',dtype={'stop_id':str})
stt=r('stop_times',dtype={'trip_id':str,'stop_id':str}); fr=r('frequencies',dtype={'trip_id':str}); sh=r('shapes',dtype={'shape_id':str})
fa=r('fare_attributes',dtype=str); fru=r('fare_rules',dtype=str)
print("== Integridade referencial")
print(" trips.route_id fora de routes:", (~tr.route_id.isin(ro.route_id)).sum())
print(" trips.shape_id fora de shapes:", (~tr.shape_id.isin(sh.shape_id)).sum())
print(" stop_times.trip_id fora de trips:", (~stt.trip_id.isin(tr.trip_id)).sum())
print(" stop_times.stop_id fora de stops:", (~stt.stop_id.isin(st.stop_id)).sum())
print(" frequencies.trip_id fora de trips:", (~fr.trip_id.isin(tr.trip_id)).sum())
print(" trips sem frequencies:", (~tr.trip_id.isin(fr.trip_id)).sum())
print(" routes sem trips:", (~ro.route_id.isin(tr.route_id)).sum())
print(" routes sem fare_rule:", (~ro.route_id.isin(fru.route_id)).sum(), " fare_rules route fora:", (~fru.route_id.isin(ro.route_id)).sum())
print(" stops (location_type 0) sem nenhuma parada em stop_times:", ((st.location_type!='1') & ~st.stop_id.isin(stt.stop_id)).sum())
print(" parent_station inexistente:", ((st.parent_station!='') & ~st.parent_station.isin(st.stop_id)).sum())
print(" stops location_type vazio:", st[st.location_type==''][['stop_id','stop_name']].values.tolist())
print("\n== Rotas por operador x route_type")
m=ro.merge(ag[['agency_id','agency_name']],how='left')
print(pd.crosstab(m.agency_name,m.route_type,margins=True))
print(" route_desc amostra:", ro.route_desc[ro.route_desc!=''].value_counts().head(15).to_dict())
print(" route_short_name prefixos:", ro.route_short_name.str.extract(r'^([A-Z]*)')[0].value_counts().to_dict())
print(" route_type 200:", ro[ro.route_type=='200'][['route_short_name','route_long_name','agency_id']].head(8).values.tolist())
print(" route_type 702:", ro[ro.route_type=='702'][['route_short_name','route_long_name']].head(8).values.tolist())
print("\n== Tarifas por rota"); print(fru.merge(fa[['fare_id','price']]).groupby(['fare_id','price']).size())
print(" fare_rules agency_id valores:", fru.agency_id.value_counts().to_dict())
# Frequencies expand
fr['s']=secs(fr.start_time); fr['e']=secs(fr.end_time); fr['h']=fr.headway_secs.astype(int)
fr['n']=np.ceil((fr.e-fr.s)/fr.h).clip(lower=0)
print("\n== Frequencies: janelas com e<=s:",(fr.e<=fr.s).sum(), " janelas >24h (end>24:00):",(fr.e>86400).sum(), " start>=24h:",(fr.s>=86400).sum())
print(" headway min/p50/max (min):", fr.h.min()/60, fr.h.median()/60, fr.h.max()/60)
print(" duracao janela (min) desc:", ((fr.e-fr.s)/60).describe().round(1).to_dict())
# overlapping windows within route/service/direction
x=fr.merge(tr,on='trip_id')
x=x.sort_values(['route_id','service_id','direction_id','shape_id','s'])
x['prev_e']=x.groupby(['route_id','service_id','direction_id','shape_id']).e.shift()
print(" janelas sobrepostas (mesma rota/servico/sentido/shape):",(x.s<x.prev_e).sum())
print(" trips por (rota,serviço,sentido) - qtd de shapes distintos >1:", (x.groupby(['route_id','service_id','direction_id']).shape_id.nunique()>1).sum())
dep=x.groupby('service_id').n.sum(); print(" partidas estimadas por tipo de dia:", dep.to_dict())
# stop_times
stt['a']=secs(stt.arrival_time); stt['d']=secs(stt.departure_time)
print("\n== stop_times: arrival!=departure:",(stt.a!=stt.d).sum(), " tempos>=24h:",(stt.a>=86400).sum())
g=stt.sort_values(['trip_id','stop_sequence']).groupby('trip_id')
agg=g.agg(n=('stop_id','size'),t0=('a','first'),t1=('a','last'),dist=('shape_dist_traveled','last'),seqmax=('stop_sequence','max'))
agg['dur']=(agg.t1-agg.t0)/60; agg['km']=agg.dist/1000; agg['kmh']=agg.km/(agg.dur/60)
print(" paradas/viagem:", agg.n.describe().round(1).to_dict())
print(" stop_sequence gaps (seqmax+1 != n):",(agg.seqmax+1!=agg.n).sum())
print(" duração (min):", agg.dur.describe(percentiles=[.01,.5,.99]).round(1).to_dict())
print(" extensão (km):", agg.km.describe(percentiles=[.01,.5,.99]).round(2).to_dict())
print(" velocidade (km/h):", agg.kmh.replace(np.inf,np.nan).describe(percentiles=[.01,.05,.5,.95,.99]).round(1).to_dict())
print(" viagens dur<=0:",(agg.dur<=0).sum(), " kmh>60:",(agg.kmh>60).sum(), " kmh<5:",(agg.kmh<5).sum())
# non-monotonic times
stt=stt.sort_values(['trip_id','stop_sequence'])
dd=stt.groupby('trip_id').a.diff(); print(" tempo regressivo entre paradas:",(dd<0).sum(), " tempo igual entre paradas consecutivas:",(dd==0).sum())
dk=stt.groupby('trip_id').shape_dist_traveled.diff(); print(" dist regressiva:",(dk<0).sum())
# same stop consecutive
print(" mesma parada consecutiva:",(stt.stop_id==stt.groupby('trip_id').stop_id.shift()).sum())
# stops geo
s0=st[st.location_type!='1']; s0lat=s0.stop_lat.astype(float); s0lon=s0.stop_lon.astype(float)
print("\n== Stops bbox lat",s0lat.min(),s0lat.max()," lon",s0lon.min(),s0lon.max())
print(" coord duplicadas (lat,lon) em >1 stop:", s0.duplicated(['stop_lat','stop_lon'],keep=False).sum())
print(" stop_id padrões:", st.stop_id.str.len().value_counts().head().to_dict())
print(" stop_desc amostra:", st.stop_desc[st.stop_desc!=''].value_counts().head(6).to_dict())
print(" estações (loc 1) amostra:", st[st.location_type=='1'].stop_name.head(10).tolist())
# shapes
shs=sh.groupby('shape_id').agg(n=('shape_pt_sequence','size'),km=('shape_dist_traveled','max')); shs.km/=1000
print("\n== shapes km:", shs.km.describe(percentiles=[.01,.5,.99]).round(2).to_dict(), " pts:", shs.n.describe().round(0).to_dict())
print(" shapes não usados por trips:", (~shs.index.isin(tr.shape_id)).sum())
# ID format mix
print(" shape_id formatos: uuid", tr.shape_id.str.len().eq(36).sum(), " curto", tr.shape_id.str.len().lt(10).sum())
print(" trips por rota (todos dias) desc:", tr.groupby('route_id').size().describe().round(1).to_dict())
print(" rotas por service_id:", tr.groupby('service_id').route_id.nunique().to_dict())
agg.to_csv(os.path.join(sys.argv[2],'trip_metrics.csv'))
x.to_csv(os.path.join(sys.argv[2],'freq_trips.csv'),index=False)
